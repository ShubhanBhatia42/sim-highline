"""Writes scripts/README.md: every script in this folder, grouped by what it is for, with the first line of its own description.
Generated; do not edit scripts/README.md by hand. Usage: python3 scripts/make-scripts-index.py"""
import ast
import re
from pathlib import Path

HERE = Path(__file__).resolve().parent

GROUPS = [
    ("Run everything", r"^(verify-all\.sh|release\.sh|coverage\.sh|reproduce\.sh|fetch_all\.sh|csp\.mjs|browser-options\.mjs)$"),
    ("Tests", r"^test[-_]"),
    ("Checks and linting", r"^(lint\.mjs|check_|audit_|validate|regress_|watch-)"),
    ("Build the site, the Explorer and the exports", r"^(build-|make-|export-|annotate-|report-|roadmap)"),
    ("The four studies and the checks made after them", r"^(analyze_|explore_|rank_|power_|make_parity|modelform_|retune)"),
    ("Put data in (ingest, digitise, extract)", r"^(ingest|digitize|digitise|extract|vector_|fetch_|pillepich|read_)"),
]


def describe(path):
    try:
        text = path.read_text(errors="replace")
    except OSError:
        return ""
    if path.suffix == ".py":
        try:
            doc = ast.get_docstring(ast.parse(text)) or ""
        except SyntaxError:
            doc = ""
        line = next((l.strip() for l in doc.splitlines() if l.strip()), "")
    else:
        line = ""
        for l in text.splitlines()[:25]:
            s = l.strip()
            if not s or s.startswith("#!") or s.startswith("import ") or s.startswith("from "):
                continue
            m = re.match(r'^(?://+|/\*+|\*|#+)\s*(.*?)\s*(?:\*/)?$', s)
            if m and m.group(1):
                line = m.group(1); break
            if s.startswith(('"""', "'''")):
                line = s.strip("\"' "); break
            if not s.startswith(("/", "*", "#")):
                break
    line = re.sub(r"\s+", " ", line).strip()
    return (line[:150] + "…") if len(line) > 150 else line


def main():
    files = sorted(p for p in HERE.iterdir() if p.is_file() and p.suffix in (".py", ".mjs", ".js", ".sh") and p.name != "README.md")
    placed, groups = set(), []
    for title, pat in GROUPS:
        members = [p for p in files if p.name not in placed and re.search(pat, p.name)]
        placed.update(p.name for p in members)
        groups.append((title, members))
    rest = [p for p in files if p.name not in placed]
    groups.append(("Everything else", rest))
    L = ["# Scripts", "",
         f"{len(files)} scripts, grouped by what they are for. Generated by `scripts/make-scripts-index.py`; the description is the first line of each script's own header. `./scripts/verify-all.sh` runs the offline checks, `make verify` runs everything, and `make help` lists the shortcuts.", ""]
    for title, members in groups:
        if not members:
            continue
        L += [f"## {title} ({len(members)})", ""]
        described = [(p, describe(p)) for p in members]
        with_text = [(p, d) for p, d in described if d]
        if with_text:
            L += ["| script | what it does |", "|---|---|"]
            L += [f"| `{p.name}` | {d.replace('|', '/')} |" for p, d in with_text]
            L.append("")
        bare = [p.name for p, d in described if not d]
        if bare:
            L += ["Without a header description (the name says what it is): " + ", ".join(f"`{n}`" for n in bare) + ".", ""]
    (HERE / "README.md").write_text("\n".join(L))
    print(f"scripts index: {len(files)} scripts in {sum(1 for _, m in groups if m)} groups")


if __name__ == "__main__":
    main()
