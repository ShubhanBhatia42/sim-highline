import { readdir, readFile, writeFile } from "node:fs/promises";
import vm from "node:vm";
const root = new URL("../", import.meta.url);
const ctx = { globalThis: {} };
vm.runInNewContext(await readFile(new URL("compare.js", root), "utf8"), ctx);
const { RULES } = ctx.globalThis.SimHighlineCompare;
const UNSET = new Set([undefined, null, "unspecified", "heterogeneous"]);
const fills = JSON.parse(await readFile(new URL("data/definition-fills.json", root), "utf8"));
const read = new Map(fills.readWithoutResult.map(r => [r.arxiv, r]));
const files = (await readdir(new URL("data/curves/", root))).filter(f => f.endsWith(".json")).sort();
const groups = new Map();
let total = 0, withFill = 0, sims = 0;
for (const f of files) for (const r of JSON.parse(await readFile(new URL(`data/curves/${f}`, root), "utf8")).records) {
  if (r.kind !== "simulation") continue;
  sims++;
  if (r.provenance.definitionFills?.length) withFill++;
  const rule = RULES[r.relation]; if (!rule) continue;
  const p = r.provenance, text = [p.url, p.citation, p.doi].join(" "), m = text.match(/arxiv\.org\/(?:abs|pdf)\/(\d{4}\.\d{4,5})/) || text.match(/arXiv:(\d{4}\.\d{4,5})/);
  const arxiv = m ? m[1] : null;
  for (const k of [...rule.hard, ...rule.soft].filter(k => k !== "cosmology")) {
    if (!UNSET.has(r.definitions[k])) continue;
    total++;
    const key = [r.source, r.relation, k, arxiv || ""].join("|");
    const g = groups.get(key) || { source: r.source, relation: r.relation, key: k, arxiv, citation: String(p.citation).replace(/,\s*(Fig\.|Figure|figure|Table).*$/, "").slice(0, 90), records: 0 };
    g.records++; groups.set(key, g);
  }
}
const list = [...groups.values()].map(g => ({ ...g, status: [...read.values()].some(r => (r.arxiv === g.arxiv || r.source === g.source) && r.keys.includes(g.key)) ? "source read, not stated" : g.arxiv ? "source not yet read for this key" : "no paper to read (data release or website)" }))
  .sort((a, b) => b.records - a.records || a.source.localeCompare(b.source));
const by = s => list.filter(g => g.status === s).reduce((a, g) => a + g.records, 0);
const summary = { simulationRecords: sims, recordsWithRecoveredDefinition: withFill, undocumentedValues: total, sourceReadNotStated: by("source read, not stated"), sourceNotYetRead: by("source not yet read for this key"), noPaperToRead: by("no paper to read (data release or website)") };
await writeFile(new URL("data/undocumented-definitions.json", root), JSON.stringify({ summary, groups: list }, null, 1) + "\n");
const rows = list.map(g => `| ${g.source} | ${g.relation} | ${g.key} | ${g.records} | ${g.arxiv ? `[${g.arxiv}](https://arxiv.org/abs/${g.arxiv})` : "-"} | ${g.status} |`);
await writeFile(new URL("docs/UNDOCUMENTED-DEFINITIONS.md", root), [
  "# Undocumented definitions", "",
  "Generated by `scripts/report-undocumented.mjs`; do not edit by hand. A value is undocumented when the record's table or figure does not state a definition that the relation's comparability rules need, and no source paper statement could be quoted for it (`data/definition-fills.json`).", "",
  `Of ${sims} simulation records, ${withFill} carry at least one definition recovered from a source paper. ${total} definition values remain undocumented: ${summary.sourceReadNotStated} where the paper was read and does not state it, ${summary.sourceNotYetRead} where the paper has not yet been read for that key, and ${summary.noPaperToRead} where the source is a data release or website without a paper to read.`, "",
  "If you are an author or data owner, a one-line statement of any of these (for example the stellar-mass aperture) is the most useful correction you can send; see CONTRIBUTING.md.", "",
  "| simulation | relation | definition | records | paper | status |", "|---|---|---|---|---|---|", ...rows, ""].join("\n"));
console.log(`Undocumented definitions: ${total} values in ${list.length} groups; ${withFill} of ${sims} simulation records carry a recovered definition`);
