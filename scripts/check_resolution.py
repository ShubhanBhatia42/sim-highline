"""Checks made AFTER the registered run of the resolution study, to help read it (they are not part of the protocol's outcomes and decide nothing): where in a curve does the shift come from, how large is the horizontal (mass) shift
that the vertical shift of a mass function amounts to, and how does the shift of the COLIBRE mass functions compare with the Poisson errors the records carry. Reads data/curves and data/analysis/resolution.json; writes
data/analysis/resolution-checks.json and docs/CHECKS-resolution.md. Usage: python3 scripts/check_resolution.py"""
import json
import sys
from collections import defaultdict
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_resolution as R

ROOT = Path(__file__).resolve().parent.parent
TAIL = 0.25          # the upper quarter of the common x range
MIN_SLOPE = 0.05     # |dy/dx| below which a point is not used for the equivalent horizontal shift


def sigma_curve(rec):
    p = sorted(rec["representation"]["points"], key=lambda q: q["x"])
    if not all("yLow" in q and "yHigh" in q for q in p):
        return None
    return np.array([q["x"] for q in p]), np.array([(q["yHigh"] - q["yLow"]) / 2 for q in p])


def unit_checks(unit, pairs, recs):
    d_all, tail_sq, tot_sq, eq, zs = [], 0.0, 0.0, [], []
    for p in pairs:
        a, b = recs[p["a"]], recs[p["b"]]
        x, d, lo, hi = R.own_grid(a, b)
        if len(x) < R.MIN_PTS:
            continue
        in_tail = x >= lo + (1 - TAIL) * (hi - lo)
        tail_sq += float(np.sum(d[in_tail] ** 2))
        tot_sq += float(np.sum(d ** 2))
        d_all.append(d[~in_tail])
        if p["relation"] == "gsmf":
            xa, ya = R.curve(a)
            slope = np.interp(x, xa, np.gradient(ya, xa)) if len(xa) > 2 else None
            if slope is not None:
                ok = np.abs(slope) >= MIN_SLOPE
                eq.extend(list(np.abs(d[ok] / slope[ok])))
        sa, sb = sigma_curve(a), sigma_curve(b)
        if sa and sb:
            s = np.hypot(np.interp(x, *sa), np.interp(x, *sb))
            zs.extend(list(d / np.maximum(s, 1e-9)))
    out = {"id": unit["id"], "ladder": unit["ladder"], "relation": unit["relation"], "rungs": f"{unit['rung_a']}>{unit['rung_b']}", "rms_dex": unit["rms_dex"], "label": unit["label"]}
    out["tail_share_of_squared_shift"] = tail_sq / tot_sq if tot_sq > 0 else None
    dd = np.concatenate(d_all) if d_all else np.array([])
    out["rms_without_tail"] = float(np.sqrt(np.mean(dd ** 2))) if len(dd) else None
    out["median_equivalent_mass_shift_dex"] = float(np.median(eq)) if eq else None
    out["rms_poisson_z"] = float(np.sqrt(np.mean(np.square(zs)))) if zs else None
    return out


def main():
    res = json.loads((ROOT / "data" / "analysis" / "resolution.json").read_text())
    recs = R.load_records()
    built, _ = R.enumerate_pairs(recs)
    by = defaultdict(list)
    for p in built:
        by[f"{p['ladder']}|{p['kind']}|{p['rung_a']}>{p['rung_b']}|{p['tok_a']}>{p['tok_b']}|{p['relation']}|{p['stem']}"].append(p)
    rows = [unit_checks(u, by[u["id"]], recs) for u in res["units"] if u["tier"] == "A" and u["kind"] == "adjacent"]
    for r, u in zip(rows, [u for u in res["units"] if u["tier"] == "A" and u["kind"] == "adjacent"]):
        r["name"] = f"{u['ladder']}: {u['rung_a']} > {u['rung_b']}, {R.rel_label(u)}"
    f = lambda v, d=2: "-" if v is None else f"{v:.{d}f}"
    mf = [r for r in rows if r["median_equivalent_mass_shift_dex"] is not None]
    pz = [r for r in rows if r["rms_poisson_z"] is not None]
    L = ["# Resolution: checks made after the run", "",
         "Generated by `scripts/check_resolution.py` from `data/analysis/resolution.json` and the curve records; do not edit by hand. **These were made after the registered run, to help read it. They are not outcomes of the protocol and decide nothing.** Internal: no outside expert has reviewed them.", "",
         "## Where in the curve does the shift come from?", "",
         f"For each tier A adjacent step: the share of the summed squared shift that lies in the upper quarter of the common x range, and the rms shift without that quarter (dex, or fraction). A large share means the shift is driven by the end of the curve (for a mass function, the steep high-mass end, where a small shift in mass is a large shift in density, and where a 25 Mpc/h box has few galaxies).", ""]
    L += R._table(["step", "rms shift (all)", "share of squared shift in the upper quarter", "rms shift without the upper quarter", "label"], [[r["name"], f(r["rms_dex"], 3), f(r["tail_share_of_squared_shift"]), f(r["rms_without_tail"], 3), r["label"]] for r in rows if r["relation"] != "sfrd"])
    L += ["", "## How large is the shift of a mass function in mass?", "",
          "For the stellar mass functions: the vertical shift divided by the local slope of the coarser curve, the median over the points of the common range (points where the slope is below 0.05 are skipped): the change in log stellar mass that would move one curve onto the other.", ""]
    L += R._table(["step", "median equivalent shift in log M* (dex)", "rms shift in log density (dex)"], [[r["name"], f(r["median_equivalent_mass_shift_dex"], 3), f(r["rms_dex"], 3)] for r in mf])
    L += ["", "## Against the Poisson errors of the COLIBRE tables", "",
          "The COLIBRE mass-function records carry Poisson errors from the published bin counts. The rms of the shift divided by the quadrature sum of the two curves' errors (not a test: runs in one box share their galaxies, so the two Poisson errors are not independent).", ""]
    L += R._table(["step", "rms (shift / Poisson error)"], [[r["name"], f(r["rms_poisson_z"])] for r in pz])
    L += ["", "## How to read this", "",
          "The registered labels use a margin of one noise unit, which is about 0.07 to 0.3 dex for the mass function depending on the mass bin: a tight margin. The tables show where in each curve the shifts sit and what a vertical shift of a mass function amounts to in mass. They do not change the registered counts.", ""]
    (ROOT / "docs" / "CHECKS-resolution.md").write_text("\n".join(L))
    (ROOT / "data" / "analysis" / "resolution-checks.json").write_text(json.dumps({"tail_fraction": TAIL, "min_slope": MIN_SLOPE, "rows": rows}, indent=1) + "\n")
    print(f"resolution checks: {len(rows)} steps")


if __name__ == "__main__":
    main()
