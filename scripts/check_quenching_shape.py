"""Checks made after the registered run of the quenching-shape study (docs/PROTOCOL-quenching-shape.md, docs/ANALYSIS-quenching-shape.md). They are not part of the registered result and change no verdict; they answer the questions a reader asks first when two
validations did not hold:
  C1  Is the point distance of the shape set stable if the search is given many more random starts (4, 8, 16, 32, 64; three seeds each)? More starts can only lower a found minimum.
  C2  Does the shape set stay removable if the noise scale holds only the seed scatter (no emulator error)? Fewer and smaller noise units make a distance larger, so this is the stricter reading.
  C3  How big are the differences in the observables' own units: the two codes at the fiducial parameters, and at the minimising setting of the shape set?
Writes data/analysis/quenching-shape-checks.json and docs/CHECKS-quenching-shape.md. Usage: python3 scripts/check_quenching_shape.py"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_joint_reachability as J
import analyze_model_form as A
import analyze_quenching_shape as Q

ROOT = Path(__file__).resolve().parent.parent
STARTS = (4, 8, 16, 32, 64)
SEEDS = 3
FAM = {"gv": "green-valley fraction (fraction)", "sfw": "width of the star-forming sequence (dex)"}


def main():
    data = Q.load()
    saved = json.loads((ROOT / "data" / "analysis" / "quenching-shape.json").read_text())
    cols = data["meta"]["columns"]
    keep, blocks, _ = J.eligibility(data)
    keep_primary = keep & np.array([c[0] != Q.WIDE for c in cols])
    idx_by_block = {b: np.array(v) for b, v in blocks.items()}
    snaps = data["meta"]["snapshots"]
    ordered = Q.block_order(blocks, snaps)
    shape_b = [b for b in ordered if b[0] in Q.SHAPE]
    emus, info = J.build_emulators(data, keep_primary, degrees=saved["meta"]["degrees"])
    scales = {"registered (seed noise and emulator error)": J.noise_scale(info), "seed noise only": J.noise_scale(info, with_emulator_error=False)}
    out = {"starts": list(STARTS), "seeds": SEEDS, "distances": {}, "native": {}}
    best = {}
    for name, sc in scales.items():
        idx, c = J.make_set(idx_by_block, shape_b, sc)
        rows = {}
        for n in STARTS:
            ds = []
            for k in range(SEEDS):
                d, a = J.distance(emus["IllustrisTNG"], emus["SIMBA"], idx, c, np.random.default_rng([Q.SEED, 91, n, k]), nstarts=n)
                ds.append(float(d))
                if name not in best or d < best[name][0]:
                    best[name] = (d, a.copy())
            rows[str(n)] = {"min": min(ds), "median": float(np.median(ds)), "max": max(ds)}
        out["distances"][name] = {"rows": rows, "D_fiducial": J.fiducial_distance(emus["IllustrisTNG"], emus["SIMBA"], idx, c), "best": float(best[name][0])}
    # native units at the fiducial parameters and at the best setting found under the registered scale
    a_best = best["registered (seed noise and emulator error)"][1]
    for fam in Q.SHAPE:
        js = np.concatenate([idx_by_block[b] for b in shape_b if b[0] == fam])
        pf_t, pf_s = A.predict_astro(emus["IllustrisTNG"], np.zeros((1, 4)))[0][js], A.predict_astro(emus["SIMBA"], np.zeros((1, 4)))[0][js]
        pb_t, pb_s = A.predict_astro(emus["IllustrisTNG"], a_best[None, :4])[0][js], A.predict_astro(emus["SIMBA"], a_best[None, 4:])[0][js]
        sn = info["IllustrisTNG"]["seed_noise"][js] ** 2 + info["SIMBA"]["seed_noise"][js] ** 2
        out["native"][fam] = {"label": FAM[fam], "n_outputs": int(len(js)), "rms_fiducial": float(np.sqrt(np.mean((pf_t - pf_s) ** 2))), "rms_best": float(np.sqrt(np.mean((pb_t - pb_s) ** 2))),
                              "one_noise_unit_seed_only": float(np.sqrt(np.mean(sn))), "max_abs_fiducial": float(np.max(np.abs(pf_t - pf_s)))}
    out["a_best"] = [float(v) for v in a_best]
    (ROOT / "data" / "analysis" / "quenching-shape-checks.json").write_text(json.dumps(out, indent=1) + "\n")
    (ROOT / "docs" / "CHECKS-quenching-shape.md").write_text(render(out))
    print("checks written")


def render(out):
    f = lambda v, d=3: f"{v:.{d}f}"
    L = ["# Checks after the registered run: quenching-shape study", "",
         "Generated by `scripts/check_quenching_shape.py`; do not edit by hand. These checks were made after the registered result existed ([`ANALYSIS-quenching-shape.md`](ANALYSIS-quenching-shape.md)), they are not part of it, and none changes a verdict. Internal: no outside expert has reviewed them.", "",
         "Two of the four validations of the registered run did not hold (V1: the emulators of the shape outputs are less accurate than the seed noise; V4: the point distance of the shape set changed by 54 % between 4 and 8 random starts). The checks below ask what that does to the answer \"removable\".", "",
         "## C1. More random starts, and the stricter noise scale", "",
         f"The point distance of the shape set (all simulations, not corrected for the emulators' variance), {out['seeds']} seeds for each number of random starts; the table gives the smallest, median and largest. More starts can only lower a minimum that was found; if the distance falls and stays well below 1 the set is reachable.", ""]
    for name, d in out["distances"].items():
        L += [f"**Noise scale: {name}.** At the fiducial parameters {f(d['D_fiducial'], 2)}; smallest distance found {f(d['best'])}.", "",
              "| random starts | smallest | median | largest |", "|---|---|---|---|"] + [f"| {n} | {f(r['min'])} | {f(r['median'])} | {f(r['max'])} |" for n, r in d["rows"].items()] + [""]
    reg, seed = out["distances"]["registered (seed noise and emulator error)"], out["distances"]["seed noise only"]
    ok = max(r["max"] for r in seed["rows"].values()) < 1.0
    L += [f"Reading: under the registered scale the distance settles at {f(reg['rows'][str(out['starts'][-1])]['median'])} (median of {out['seeds']} runs with {out['starts'][-1]} starts). Under the stricter scale without the emulators' error it is {f(seed['rows'][str(out['starts'][-1])]['median'])}, " + ("still below the margin of 1: the shape set stays reachable if the emulators' error is not allowed to widen the noise unit." if ok else "not below the margin of 1 for every run: the verdict removable depends on the emulators' error being part of the noise scale, which is a limit of this study.") + "", "",
          "## C2. The differences in the observables' own units", "",
          "Root mean square difference between IllustrisTNG and SIMBA over the eligible outputs of each family: at the fiducial parameters, and at the setting of both codes' dials that gave the smallest registered distance. One noise unit (seed scatter only, summed for the two codes) for scale.", "",
          "| observable | outputs | at fiducial | largest single output at fiducial | at the best setting | one noise unit (seed scatter) |", "|---|---|---|---|---|---|"]
    L += [f"| {n['label']} | {n['n_outputs']} | {f(n['rms_fiducial'])} | {f(n['max_abs_fiducial'])} | {f(n['rms_best'])} | {f(n['one_noise_unit_seed_only'])} |" for n in out["native"].values()]
    L += ["", f"Coordinates of the best setting (half-range units, -1 to 1): IllustrisTNG {', '.join(f'{v:+.2f}' for v in out['a_best'][:4])}; SIMBA {', '.join(f'{v:+.2f}' for v in out['a_best'][4:])}. A coordinate at the edge of the range is where the emulators are least constrained.", "",
          "## What these checks do not do", "", "They do not calibrate the estimators for this layout of outputs, they do not add a resolution test, and they use the same two codes, the same boxes and the same emulators as the registered run.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
