"""Exploratory: are the emulators trustworthy where the registered search put its minimum? That minimum sits at the edge of the dial box (4 of 8 coordinates on a bound), where the emulators are least constrained and where the cross-validation that sets the noise scale (simulations near the fiducial cosmology) says least.
For each code: take the simulations whose four astrophysical coordinates are nearest the code's minimising setting, refit the emulator WITHOUT them, predict them, and compare the error (in the analysis' noise units, over the outputs of the all-at-once set) with the same procedure for simulations nearest the fiducial point and for random simulations. This does not run a new simulation at the minimum (none exists); it asks whether held-out simulations in that corner are predicted worse than elsewhere.
Writes data/analysis/minimiser-check.json and docs/ANALYSIS-minimiser-check.md. Usage: python3 scripts/explore_minimiser_check.py"""
import json
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_joint_reachability as J
import analyze_model_form as A

ROOT = Path(__file__).resolve().parent.parent
K = 15


def main():
    data = J.load_galaxies()
    keep, blocks, _ = J.eligibility(data)
    emus, info = J.build_emulators(data, keep)
    scale = J.noise_scale(info)
    reg = json.loads((ROOT / "data" / "analysis" / "joint-reachability.json").read_text())["point"]["all"]
    mins = {"IllustrisTNG": np.array(reg["a_tng"]), "SIMBA": np.array(reg["a_simba"])}
    joint_cols = np.array(sorted({j for b, v in blocks.items() if b[0] != "hmf" for j in v}))
    rng = np.random.default_rng(20261022)
    out = {"k": K, "outputs": int(len(joint_cols)), "codes": {}}
    for code in J.SUITES:
        lh = data["suites"][code]["LH"]
        X, Y = lh["X"], lh["Y"]
        deg = info[code]["degree"]
        sets = {"nearest the minimising setting": np.argsort(np.linalg.norm(X[:, 2:] - mins[code], axis=1))[:K],
                "nearest the fiducial setting": np.argsort(np.linalg.norm(X[:, 2:], axis=1))[:K],
                "random simulations": rng.choice(len(X), K, replace=False)}
        res = {}
        for name, idx in sets.items():
            tr = np.ones(len(X), bool)
            tr[idx] = False
            emu = A.fit_emulator(X[tr], Y[tr], deg)
            P = emu.predict(X[idx])
            z = (P - Y[idx])[:, joint_cols] / scale[joint_cols]
            ok = np.isfinite(z)
            per_sim = np.sqrt(np.nanmean(np.where(ok, z, np.nan) ** 2, axis=1))
            dist = np.linalg.norm(X[idx][:, 2:] - (mins[code] if name.startswith("nearest the min") else np.zeros(4)), axis=1)
            res[name] = {"rms_noise_units": float(np.sqrt(np.nanmean(z[ok] ** 2))), "median_per_simulation": float(np.median(per_sim)), "mean_signed": float(np.nanmean(z[ok])), "mean_distance_in_dial_coordinates": float(dist.mean()) if not name.startswith("random") else None}
        out["codes"][code] = {"minimiser": mins[code].round(3).tolist(), "degree": deg, "sets": res}
    (ROOT / "data" / "analysis" / "minimiser-check.json").write_text(json.dumps(out, indent=1) + "\n")
    L = ["# Are the emulators trustworthy at the registered minimum? (exploratory)", "",
         "Generated by `scripts/explore_minimiser_check.py` after the registered run; it changes no verdict. The registered search puts its minimum at the edge of the dial box (4 of the 8 dial coordinates on a bound), where the emulators are least constrained. For each code, the %d simulations whose dial settings are nearest the minimising setting were **held out**, the emulator was refitted without them, and their predicted outputs were compared with what the simulations actually gave, in the analysis' noise units over the %d outputs of the all-at-once set. The same was done for the %d simulations nearest the fiducial setting and for %d random simulations. A single simulation's own seed scatter is part of every number (about 0.7 noise units is what perfect emulation would give), so the comparison between rows is what matters." % (K, out["outputs"], K, K), "",
         "| code | simulations | held-out rms error (noise units) | median per simulation | mean signed error | mean distance from the target setting (dial coordinates, 4-D) |", "|---|---|---|---|---|---|"]
    for code, r in out["codes"].items():
        for name, v in r["sets"].items():
            d = v["mean_distance_in_dial_coordinates"]
            L.append(f"| {code} | {name} | {v['rms_noise_units']:.2f} | {v['median_per_simulation']:.2f} | {v['mean_signed']:+.2f} | {'' if d is None else f'{d:.2f}'} |")
    L += ["", "## Reading", "",
          "If the corner rows are close to the others, held-out simulations there are predicted about as well as anywhere, and the emulators' own error does not by itself explain the distance. If they are clearly worse, the distance at the edge is less certain than the half-sample ranges say. Two limits: the nearest simulations are not *at* the minimum (the distance column says how far they are; a six-parameter Latin hypercube of 1,000 points is sparse in a corner), and the simulations nearest the minimum differ in cosmology too, which the emulator is asked to handle as well. This is a check on prediction error near the corner, not a simulation at the minimum.", ""]
    (ROOT / "docs" / "ANALYSIS-minimiser-check.md").write_text("\n".join(L))
    for code, r in out["codes"].items():
        print(code, {k: round(v["rms_noise_units"], 2) for k, v in r["sets"].items()})


if __name__ == "__main__":
    main()
