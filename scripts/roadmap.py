"""Roadmap bookkeeping. Usage:
  python3 scripts/roadmap.py done 1.01 1.02 -n "note"       mark tasks done (optional note, same for all)
  python3 scripts/roadmap.py partial 4.01 -n "what is missing"
  python3 scripts/roadmap.py blocked 2.12 -n "why"
  python3 scripts/roadmap.py skip 6.13 -n "why not"
  python3 scripts/roadmap.py render                           write docs/ROADMAP.md and data/roadmap.json
Statuses: todo (default), done, partial, blocked (needs a person), skipped."""
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from roadmap_tasks import STEPS, T

ROOT = Path(__file__).resolve().parent.parent
STATUS = ROOT / "data" / "roadmap-status.json"
TIER = {1: "Quick (under 15 min)", 2: "Solid (about an hour)", 3: "Big (several hours)", 4: "Needs other people or days"}
WHO = {"C": "Build", "U": "Maintainer", "B": "Both"}
MARK = {"todo": "[ ]", "done": "[x]", "partial": "[~]", "blocked": "[!]", "skipped": "[-]"}


def load():
    return json.loads(STATUS.read_text()) if STATUS.exists() else {}


def render():
    st = load()
    tasks = [{"id": i, "step": int(i.split(".")[0]), "tier": t, "who": w, "title": title, **st.get(i, {"status": "todo"})} for i, t, w, title in T]
    (ROOT / "data" / "roadmap.json").write_text(json.dumps(tasks, indent=1) + "\n")
    count = lambda f: sum(1 for t in tasks if f(t))
    L = ["# Roadmap: from useful to great", "", "Generated by `scripts/roadmap.py` from `scripts/roadmap_tasks.py` and `data/roadmap-status.json`; do not edit by hand.", "",
         "Ten steps, 200 tasks. Tier 1 is quick, tier 2 about an hour, tier 3 several hours, tier 4 needs other people or days. `[x]` done, `[~]` partly done, `[!]` waiting for a person, `[-]` decided against, `[ ]` not done.", ""]
    L += ["| tier | tasks | done | partly | waiting for a person | not done |", "|---|---|---|---|---|---|"]
    for tier in (1, 2, 3, 4):
        f = lambda t, tier=tier: t["tier"] == tier
        L.append(f"| {tier} {TIER[tier]} | {count(f)} | {count(lambda t: f(t) and t['status'] == 'done')} | {count(lambda t: f(t) and t['status'] == 'partial')} | {count(lambda t: f(t) and t['status'] == 'blocked')} | {count(lambda t: f(t) and t['status'] in ('todo', 'skipped'))} |")
    L.append(f"| all | {len(tasks)} | {count(lambda t: t['status'] == 'done')} | {count(lambda t: t['status'] == 'partial')} | {count(lambda t: t['status'] == 'blocked')} | {count(lambda t: t['status'] in ('todo', 'skipped'))} |")
    for s, (name, why) in STEPS.items():
        ts = [t for t in tasks if t["step"] == s]
        L += ["", f"## Step {s}. {name}", "", f"*{why}* ({count(lambda t: t['step'] == s and t['status'] == 'done')} of {len(ts)} done)", ""]
        for t in ts:
            note = f" — {t['note']}" if t.get("note") else ""
            L.append(f"- {MARK[t['status']]} **{t['id']}** · tier {t['tier']} · {WHO[t['who']]} · {t['title']}{note}")
    (ROOT / "docs" / "ROADMAP.md").write_text("\n".join(L) + "\n")


def main(argv):
    if not argv or argv[0] == "render":
        render()
        return
    cmd, ids, note = argv[0], [], None
    i = 1
    while i < len(argv):
        if argv[i] == "-n":
            note = argv[i + 1]
            i += 2
        else:
            ids.append(argv[i])
            i += 1
    valid = {t[0] for t in T}
    bad = [x for x in ids if x not in valid]
    assert cmd in ("done", "partial", "blocked", "skip") and not bad, f"bad command or ids {bad}"
    st = load()
    for x in ids:
        st[x] = {"status": "skipped" if cmd == "skip" else cmd, **({"note": note} if note else {})}
    STATUS.write_text(json.dumps(st, indent=1, sort_keys=True) + "\n")
    render()


if __name__ == "__main__":
    main(sys.argv[1:])
