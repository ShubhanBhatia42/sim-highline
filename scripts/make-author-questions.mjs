// Writes docs/AUTHOR-QUESTIONS.md: for each simulation, the definitions that no paper states for its records (from data/undocumented-definitions.json), as one short question per paper that its authors can answer in a line, plus one message to adapt. Nothing is sent. Generated; do not edit by hand.
import fs from "node:fs";

const ROOT = new URL("../", import.meta.url).pathname;
const U = JSON.parse(fs.readFileSync(ROOT + "data/undocumented-definitions.json", "utf8"));
const ASK = {
  massDefinition: "Which stellar mass is plotted: all stars bound to the subhalo, or the stars within an aperture (which one: a fixed physical radius, a multiple of the half-mass radius, or something else)?",
  imf: "Which initial mass function do the stellar masses and star formation rates assume (and were they converted)?",
  densityFrame: "Are the number densities per comoving or per physical volume?",
  sfrTimescaleMyr: "Over what time are star formation rates averaged (instantaneous, or the last N Myr)?",
  sfrIndicator: "How is the star formation rate defined (simulation SFR of the gas, or from the stars formed in the last N Myr, or from the model's UV and infrared luminosity)?",
  haloMassHistory: "Is the halo mass taken at the same epoch as the galaxy, or the peak or another epoch?",
  haloMassDefinition: "How is the halo mass defined (M200 critical, M200 mean, a virial mass, FOF)?",
  bhMassMethod: "Is the black hole mass the dynamical or the accretion-model mass, and is it summed or the central black hole?",
  population: "Which galaxies are included (all, centrals only, a mass or SFR cut)?",
  sfrIntegrationLimit: "Down to which luminosity or SFR is the density integrated?",
  dustCorrection: "Are the luminosities attenuated by dust, and with which model?",
};
const by = new Map();
for (const g of U.groups) {
  if (!by.has(g.source)) by.set(g.source, []);
  by.get(g.source).push(g);
}
const L = ["# Questions for authors", "",
  "*Generated by `scripts/make-author-questions.mjs` from `data/undocumented-definitions.json`; do not edit by hand. **Nothing here has been sent.***", "",
  `${U.summary.undocumentedValues} definition values are not stated by the papers behind the records (${U.summary.sourceReadNotStated} where the paper was read and does not state it). Each unanswered one stops some curves from being called comparable with others. A one-line answer from an author or data owner is the most useful correction anyone can send. Below, per simulation, the papers and the questions; the message to adapt comes first.`, "",
  "## The message", "",
  "> Subject: One-line question about a definition in *[paper]*",
  ">",
  "> Hello [name], I maintain sim-highline (https://shubhanbhatia42.github.io/sim-highline/), an open dataset of published galaxy scaling relations with the definitions that decide whether two curves can be compared. For the curves from your paper *[title, arXiv number]* I could not find, in the paper, the answer to the question(s) below. Could you reply with a line, or point me to the sentence or data page that states it? I will record the answer with your name if you agree and cite the sentence; if you prefer not to be named, I will record it as a private communication. If a curve of yours is wrong, I will correct it and credit the report.",
  ">",
  "> [questions]",
  ">",
  "> Thank you, [your name]", ""];
for (const [src, gs] of [...by].sort((a, b) => a[0].localeCompare(b[0]))) {
  const n = gs.reduce((t, g) => t + g.records, 0);
  L.push(`## ${src}`, "", `${gs.length} open definition${gs.length === 1 ? "" : "s"} across ${n} record${n === 1 ? "" : "s"}.`, "");
  const papers = new Map();
  for (const g of gs) { const k = g.arxiv || g.citation; if (!papers.has(k)) papers.set(k, { g, items: [] }); papers.get(k).items.push(g); }
  for (const [k, { g, items }] of papers) {
    const head = g.arxiv ? `[arXiv:${g.arxiv}](https://arxiv.org/abs/${g.arxiv})` : `${g.citation} (no paper to read: a data release or website)`;
    L.push(`**${head}**`, "");
    const byKey = new Map();
    for (const it of items) { if (!byKey.has(it.key)) byKey.set(it.key, []); byKey.get(it.key).push(it); }
    for (const [key, its] of byKey) L.push(`- *${key}*: ${ASK[key] || "What does this mean for the plotted curve?"} (relations: ${[...new Set(its.map(i => i.relation))].join(", ")}; ${its.reduce((t, i) => t + i.records, 0)} records)`);
    L.push("");
  }
}
fs.writeFileSync(ROOT + "docs/AUTHOR-QUESTIONS.md", L.join("\n"));
console.log(`author questions: ${by.size} simulations, ${U.groups.length} open definitions`);
