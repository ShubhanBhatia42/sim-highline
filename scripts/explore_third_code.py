"""Exploratory: a third simulation code. Does the registered all-at-once result (IllustrisTNG against SIMBA) look the same when the third CAMELS code, Astrid, is added, and which pair of the three is furthest apart on what?
Made after the registered run and not part of it; nothing here changes a verdict. Same machinery as the registered analysis (polynomial emulators per code, noise-unit scale, distance searched over the dials of both codes), run on each of the three pairs over the observables that are usable in all three codes, so that the pairs are comparable with each other. The distances are uncorrected point estimates, the same kind of number as the registered point distance.
Needs data/ensembles/camels-galaxies.json and camels-galaxies-astrid.json (scripts/ingest_camels_galaxies.py). Writes data/analysis/third-code.json and docs/ANALYSIS-third-code.md. Usage: python3 scripts/explore_third_code.py"""
import itertools
import json
import sys
import tempfile
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_joint_reachability as J

ROOT = Path(__file__).resolve().parent.parent
CODES = ("IllustrisTNG", "SIMBA", "Astrid")
SHORT = {"IllustrisTNG": "TNG", "SIMBA": "SIMBA", "Astrid": "Astrid"}


def merged_data():
    a = json.loads((ROOT / "data" / "ensembles" / "camels-galaxies.json").read_text())
    b = json.loads((ROOT / "data" / "ensembles" / "camels-galaxies-astrid.json").read_text())
    assert a["snapshots"] == b["snapshots"] and a["familyBins"] == b["familyBins"], "the two files must share their grids"
    a["suites"]["Astrid"] = b["suites"]["Astrid"]
    with tempfile.NamedTemporaryFile("w", suffix=".json", delete=False) as f:
        json.dump(a, f)
    try:
        return J.load_galaxies(f.name)
    finally:
        Path(f.name).unlink()


def pair_scale(info, x, y):
    v = info[x]["seed_noise"] ** 2 + info[y]["seed_noise"] ** 2 + info[x]["emulator_error"] ** 2 + info[y]["emulator_error"] ** 2
    return np.maximum(np.sqrt(v), J.FLOOR)


def main():
    J.SUITES = CODES  # loading, eligibility and the emulators then cover all three codes, so that every pair uses the same outputs
    data = merged_data()
    keep, blocks, detail = J.eligibility(data)
    emus, info = J.build_emulators(data, keep)
    ibb = {b: np.array(v) for b, v in blocks.items()}
    joint = [b for b in blocks if b[0] != "hmf"]
    fams = [f for f in J.JOINT_FAMILIES if any(b[0] == f for b in joint)]
    rng = np.random.default_rng(20261019)
    reg = json.loads((ROOT / "data" / "analysis" / "joint-reachability.json").read_text())
    out = {"codes": list(CODES), "families": fams, "n_blocks": len(joint), "n_outputs": int(sum(len(blocks[b]) for b in joint)), "registered_all": reg["point"]["all"]["D"], "registered_outputs": int(reg["meta"]["n_outputs_eligible"]),
           "degree": {c: info[c]["degree"] for c in CODES}, "finite_lh": {c: float(np.mean(detail[c]["finite_lh"][keep])) for c in CODES}, "pairs": {}}
    for x, y in itertools.combinations(CODES, 2):
        scale = pair_scale(info, x, y)
        row = {}
        for name, ks in [("all", joint)] + [(f, [b for b in joint if b[0] == f]) for f in fams]:
            if not ks:
                continue
            idx, c = J.make_set(ibb, ks, scale)
            d, a = J.distance(emus[x], emus[y], idx, c, rng, nstarts=10)
            row[name] = {"D": float(d), "fiducial": J.fiducial_distance(emus[x], emus[y], idx, c), "dials_x": [round(float(v), 2) for v in a[:4]], "dials_y": [round(float(v), 2) for v in a[4:]]}
        out["pairs"][f"{x}|{y}"] = row
    (ROOT / "data" / "analysis" / "third-code.json").write_text(json.dumps(out, indent=1) + "\n")
    (ROOT / "docs" / "ANALYSIS-third-code.md").write_text(render(out))
    p = out["pairs"]
    print("third code:", ", ".join(f"{k.replace('|', ' vs ')} {v['all']['D']:.2f}" for k, v in p.items()), f"({out['n_outputs']} outputs in {out['n_blocks']} blocks)")


def render(o):
    N = J.FAMILY_NAMES
    pairs = list(o["pairs"])
    L = ["# A third code: Astrid (exploratory)", "",
         "Generated by `scripts/explore_third_code.py`, made **after** the registered all-at-once run. It is not part of that result and changes none of its verdicts. The question: does the picture change when the third CAMELS code is added, and which pair of codes is furthest apart on which property?", "",
         f"Method: the registered machinery (one polynomial emulator per code, differences measured in noise units, the dials of both codes searched for the smallest distance), run on each of the three pairs over the {o['n_outputs']} outputs ({o['n_blocks']} blocks) that are usable in all three codes, so the pairs are comparable with one another. Distances are uncorrected point estimates, as in the registered point distance. The usable set is smaller than the registered two-code set whenever Astrid lacks an output, so the TNG–SIMBA number here is not the registered 4.8: " + (f"the registered run used {o['registered_outputs']} outputs and gave {o['registered_all']:.2f}; " if o.get("registered_outputs") else f"the registered run gave {o['registered_all']:.2f} over a larger set; ") + "the comparison that matters here is between the three pairs on the same outputs.", "",
         "Emulator degree per code: " + ", ".join(f"{SHORT[c]} {d}" for c, d in o["degree"].items()) + ". Share of simulations with a finite value over the shared outputs: " + ", ".join(f"{SHORT[c]} {v:.0%}" for c, v in o["finite_lh"].items()) + ".", "",
         "## Distance after the best retuning of both codes (noise units)", "", "| set | " + " | ".join(p.replace("|", " vs ") for p in pairs) + " |", "|---|" + "---|" * len(pairs)]
    names = ["all"] + o["families"]
    for n in names:
        cells = []
        for p in pairs:
            r = o["pairs"][p].get(n)
            cells.append(f"{r['D']:.2f}" if r else "–")
        L.append(f"| {'all observables' if n == 'all' else N[n]} | " + " | ".join(cells) + " |")
    L += ["", "## Reading", ""]
    d = {p: o["pairs"][p]["all"]["D"] for p in pairs}
    far = max(d, key=d.get); near = min(d, key=d.get)
    L.append(f"Over all shared observables the pairs are {', '.join(f'{p.replace(chr(124), chr(32) + chr(118) + chr(115) + chr(32))} {v:.1f}' for p, v in d.items())} noise units. The furthest pair is {far.replace('|', ' vs ')} and the nearest is {near.replace('|', ' vs ')}.")
    L.append("")
    structural = []
    for n in o["families"]:
        vals = {p: o["pairs"][p][n]["D"] for p in pairs if n in o["pairs"][p]}
        if len(vals) == len(pairs) and min(vals.values()) > 1.0:
            structural.append(N[n])
    odd = {}
    for n in o["families"]:
        vals = {p: o["pairs"][p][n]["D"] for p in pairs if n in o["pairs"][p]}
        if len(vals) != len(pairs):
            continue
        far = [p for p, v in vals.items() if v > 1.0]
        if len(far) == 2:
            common = set(far[0].split("|")) & set(far[1].split("|"))
            odd[n] = SHORT[common.pop()]
    if odd:
        L.append("Properties where one code stands apart (both of its pairs more than one noise unit apart, the other pair not): " + "; ".join(f"{N[n]} — {c}" for n, c in odd.items()) + ". With so few outputs in some of these properties, read this as a lead, not a finding.")
        L.append("")
    L.append("Properties still more than one noise unit apart in **every** pair, after the best retuning of each (the candidates for a difference that is built into the codes' models and not a matter of dial settings): " + (", ".join(structural) if structural else "none") + ".")
    L += ["", "A distance over one noise unit means the two codes' curves cannot be brought within the run-to-run scatter by turning the four dials, at the usual caveats: the dials are only four of the things that differ, the emulators have their own error (included in the noise scale) and the point estimate is not corrected for emulator noise, so small distances are upward-biased.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
