"""Calibration of the joint-reachability estimators of docs/PROTOCOL-joint-reachability.md on synthetic two-code worlds. No real catalogue is read here, so nothing in this file depends on an outcome of the analysis.

A world has two codes with the same family and snapshot structure as the real data (blocks of outputs), four parameters per code with known linear and weakly quadratic responses (parametric spread of about three noise
units), seed scatter 0.1 and 1000 (or fewer) Latin-hypercube-like simulations plus 27 seeds per code. Kinds:
  identical   both codes have the same responses and baseline
  shift       one family of the second code is shifted by a known amount that no parameter pair can absorb (the responses are random, the shift is the same for every output of the family)
  conflict    every family is reachable alone, but by a different parameter pair for each family, so no single pair serves all
Writes data/analysis/joint-reachability-power.json and docs/POWER-joint-reachability.md. Usage: python3 scripts/power_joint_reachability.py [--quick]   (about 20 minutes on four cores; --quick runs a smoke-sized version)."""
import argparse
import json
import multiprocessing as mp
import sys
import time
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import analyze_joint_reachability as J
import analyze_model_form as A
import ingest_camels_galaxies as G

ROOT = Path(__file__).resolve().parent.parent
SEED = 20261017


def world(kind, seed, n_lh=1000, n_cv=27, snaps=("090", "062"), shift=0.0, shift_family="bhocc", noise=0.1, resp=0.25):
    """A synthetic dataset in the structure of `load_galaxies`."""
    cols = [(f, s, b) for s in snaps for f in J.FAMILIES for b in range(G.FAMILY_BINS[f])]
    P = len(cols)
    r = np.random.default_rng(seed)
    base = r.uniform(-1, 1, P)
    RT = r.normal(0, resp, (P, 4))
    RS = RT.copy() if kind != "conflict" else r.normal(0, resp, (P, 4))
    QT = r.normal(0, 0.03, (P, 4))
    fam_idx = {f: np.array([j for j, (g, s, b) in enumerate(cols) if g == f]) for f in J.FAMILIES}
    off = np.zeros(P)
    if kind == "shift":
        off[fam_idx[shift_family]] = shift
    if kind == "conflict":
        # each family reachable alone: S minus T is the difference of the two responses at a family-specific parameter pair
        for f, ix in fam_idx.items():
            u, v = r.uniform(-1, 1, 4), r.uniform(-1, 1, 4)
            off[ix] = (RT[ix] @ u) - (RS[ix] @ v)
    suites = {}
    for code, R, o in (("IllustrisTNG", RT, np.zeros(P)), ("SIMBA", RS, off)):
        rr = np.random.default_rng([seed, 1 if code == "IllustrisTNG" else 2])

        def sims(n, fixed):
            X = np.zeros((n, 6)) if fixed else rr.uniform(-1, 1, (n, 6))
            a = X[:, 2:]
            Y = base[None, :] + o[None, :] + a @ R.T + (a ** 2) @ QT.T + 0.05 * X[:, :1] + rr.normal(0, noise, (n, P))
            return {"X": X, "Y": Y, "names": [f"S_{i}" for i in range(n)]}
        suites[code] = {"LH": sims(n_lh, False), "CV": sims(n_cv, True)}
    return {"meta": {"snapshots": list(snaps), "z": {"090": 0.0, "062": 0.95}, "columns": cols, "families": J.FAMILIES}, "suites": suites}


def one(args):
    kind, shift, rep, seed, n_lh, nsplit = args
    data = world(kind, seed + rep, n_lh=n_lh, shift=shift)
    res = J.run(data=data, nsplit=nsplit, nsmall=max(4, nsplit // 2), npath=max(3, nsplit // 3), nstarts=3, sens=False)
    v = J.verdicts({**res, "verdicts": None, "version": "x"}) if False else None
    s, p = res["splits"], res["point"]
    fam = {f: s["fam:" + f]["verdict"] for f in J.JOINT_FAMILIES if s.get("fam:" + f)}
    j3 = res.get("J3") or {}
    return {"kind": kind, "shift": shift, "rep": rep, "J1": s["all"]["verdict"], "D_all": p["all"]["D"], "between_p5": s["all"]["between"]["p5"], "control_p95": s["all"]["control"]["p95"], "J2": fam,
            "J2_structural": [f for f, x in fam.items() if x == "structural"], "ratio": j3.get("ratio_point"), "separating": (res.get("separating_set") or {}).get("families"), "path": [x["family"] for x in res["greedy_path"]]}


def run(quick):
    t0 = time.time()
    n_lh, nsplit, reps = (300, 6, 1) if quick else (1000, 40, 3)
    jobs = []
    seed = SEED
    for shift in ((0.0, 0.8) if quick else (0.0, 0.15, 0.3, 0.6, 1.2)):
        for rep in range(reps):
            jobs.append(("shift" if shift else "identical", shift, rep, seed + 100 * int(shift * 100), n_lh, nsplit))
    for rep in range(reps):
        jobs.append(("conflict", 0.0, rep, seed + 7000, n_lh, nsplit))
    with mp.Pool(4) as pool:
        rows = pool.map(one, jobs)
    return {"seed": SEED, "quick": quick, "rows": rows, "elapsed_s": round(time.time() - t0)}


def render(out):
    L = ["# Calibration of the joint-reachability estimators on synthetic worlds", "",
         "Generated by `scripts/power_joint_reachability.py` (seed %d); nothing here reads a real catalogue. Protocol: [`PROTOCOL-joint-reachability.md`](PROTOCOL-joint-reachability.md), section 6." % out["seed"], "",
         "Two codes, each with 1000 simulations over four parameters and 27 seeds, seed scatter 0.1, the block structure of the real data at two redshifts, parametric responses of about three noise units. *shift*: the second code's black hole occupation family is shifted by the stated amount (in the units of the outputs; the noise scale is about 0.15); *conflict*: every family is reachable alone by a different parameter pair.", "",
         "| world | shift | runs | joint verdict | median D(all) | families structural alone | J3 ratio (median) | separating set |", "|---|---|---|---|---|---|---|---|"]
    keys = sorted({(r["kind"], r["shift"]) for r in out["rows"]}, key=lambda k: (k[0] != "identical", k[0], k[1]))
    for kind, shift in keys:
        rs = [r for r in out["rows"] if r["kind"] == kind and r["shift"] == shift]
        cnt = ", ".join(f"{v} {sum(1 for r in rs if r['J1'] == v)}" for v in sorted({r["J1"] for r in rs}))
        st = {}
        for r in rs:
            for f in r["J2_structural"]:
                st[f] = st.get(f, 0) + 1
        sep = [", ".join(r["separating"]) if r["separating"] else "none" for r in rs]
        L.append(f"| {kind} | {shift} | {len(rs)} | {cnt} | {np.median([r['D_all'] for r in rs]):.2f} | {', '.join(f'{f} ({n}/{len(rs)})' for f, n in sorted(st.items())) or 'none'} | {np.median([r['ratio'] for r in rs if r['ratio'] is not None]):.2f} | {'; '.join(sep)} |")
    L += ["", "`python3 scripts/power_joint_reachability.py` rewrites this file and `data/analysis/joint-reachability-power.json`.", ""]
    return "\n".join(L)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--quick", action="store_true")
    args = ap.parse_args()
    out = run(args.quick)
    if args.quick:
        print(render(out))
        return
    (ROOT / "data" / "analysis" / "joint-reachability-power.json").write_text(json.dumps(out, indent=1, default=lambda o: float(o) if isinstance(o, np.floating) else int(o) if isinstance(o, np.integer) else str(o)) + "\n")
    (ROOT / "docs" / "POWER-joint-reachability.md").write_text(render(out))
    print("written; elapsed", out["elapsed_s"], "s")


if __name__ == "__main__":
    main()
