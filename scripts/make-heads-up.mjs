import { readFile, readdir, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const release = JSON.parse(await readFile(new URL("data/release.json", root), "utf8"));
const rules = JSON.parse(await readFile(new URL("data/source-terms.json", root), "utf8")).rules;
const bySuite = new Map(), flagged = new Map();
const short = c => (c.match(/^(.+? \d{4}, [^,]+? \d+, [A-Za-z0-9]+)/) || [0, c.split(" (")[0]])[1].replace(/, (Figure|Fig\.|Table).*$/, "");
for (const f of (await readdir(new URL("data/curves/", root))).filter(f => f.endsWith(".json"))) {
  for (const r of JSON.parse(await readFile(new URL(`data/curves/${f}`, root), "utf8")).records) {
    const p = r.provenance;
    if (r.kind === "simulation" && p.tier === "digitized-figure") {
      const e = bySuite.get(r.source) || bySuite.set(r.source, { n: 0, rel: new Set(), z: [], papers: new Map() }).get(r.source);
      e.n++; e.rel.add(r.relation); e.z.push(r.epoch.zRepresentative);
      const k = short(p.citation); e.papers.set(k, (e.papers.get(k) || 0) + 1);
    }
    if (p.terms && /third-party/.test(p.terms)) { const e = flagged.get(p.terms) || flagged.set(p.terms, { n: 0 }).get(p.terms); e.n++; }
  }
}
const zr = z => { const s = [...new Set(z)].sort((a, b) => a - b); return s.length > 1 ? `z = ${+s[0].toFixed(2)} to ${+s[s.length - 1].toFixed(2)}` : `z = ${+s[0].toFixed(2)}`; };
const suites = [...bySuite.entries()].filter(([, e]) => e.n >= 5).sort((a, b) => b[1].n - a[1].n || a[0].localeCompare(b[0]));
const L = [
  "# Drafts: a heads-up to the authors before the repository goes public",
  "",
  `Generated by \`scripts/make-heads-up.mjs\` from dataset v${release.version}. Nothing here has been sent. Replace \`[REPO URL]\` with the public link, address each draft to the first author(s) of the papers listed, and send from your own account. \`docs/author-requests.md\` is the longer, per-paper request for released tables; these are the short courtesy notes.`,
  "",
  "## What every note says",
  "",
  "1. What sim-highline is and that it is an unreviewed beta, about half digitized from published figures.",
  "2. Which of their curves it holds, read from the vector paths of the paper's own figure, with the citation and DOI on every record.",
  "3. Four asks: is the reading right; is the citation the one you want; any objection to the curves being included (they will be removed on request); and, if a table exists, a link so the records can become exact.",
  "",
  "## Permission requests (do these first)",
  "",
  ...[...flagged.entries()].map(([t, e]) => `- **${e.n} records** are flagged \`${t}\`.`),
  "",
  "> Dear Dr X, I maintain sim-highline, an open dataset of galaxy scaling relations (CC BY 4.0 for the compilation, code MIT, [REPO URL]). It includes values derived from your released data [name the repository or release]. The release carries [GPL-2.0 / no licence file], so I have flagged those records as third-party in the dataset and kept them out of the CC BY part. Would you be happy for the derived values to be redistributed with attribution, and under which terms? If you prefer, I will remove them. Thank you for releasing the data.",
  "",
  "## One note per suite (most digitized records first)",
  ""
];
for (const [s, e] of suites) {
  const papers = [...e.papers.entries()].sort((a, b) => b[1] - a[1] || a[0].localeCompare(b[0]));
  L.push(`### ${s}`, "", `${e.n} digitized records, relations ${[...e.rel].sort().join(", ")}, ${zr(e.z)}. Papers: ${papers.map(([k, n]) => `${k} (${n})`).join("; ")}.`, "",
    `> Dear Dr X, before I make sim-highline public ([REPO URL]; an open, citation-first dataset of galaxy scaling relations, currently an unreviewed beta) I wanted to let you know it contains ${e.n} curves read from the published figures of ${s}: ${papers.slice(0, 4).map(([k]) => k).join("; ")}${papers.length > 4 ? "; and others" : ""}. Each record cites the paper and DOI, states the definitions used (mass aperture, IMF, population), and is marked as digitized and not rankable. Could you tell me (1) whether the values and definitions look right, (2) whether you want a different citation, (3) whether you object to the curves being included (I will remove them on request), and (4) whether a table exists that I could use instead? Thank you, Shubhan Bhatia`, "");
}
await writeFile(new URL("docs/author-heads-up.md", root), L.join("\n"));
console.log(`Heads-up drafts: ${suites.length} suites, ${flagged.size} permission requests`);
