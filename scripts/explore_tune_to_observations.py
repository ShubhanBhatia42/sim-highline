"""Exploratory: after tuning its four dials to a published observed curve, how far is each code from it?
For every observed curve on the dials page (data/retune/retune.json, overlays of kind "observation"), each code's dials are searched (scipy L-BFGS-B from many starts, a second implementation of the page's search) for the setting that reproduces the curve on the simulated mass bins it covers, at the redshift of the snapshot. The leftover is reported in dex (the unit of the curve) and in the page's noise units.
This is NOT a test of either code: an observed curve is defined differently from the simulated one (aperture, IMF, population selection, what counts as a galaxy), so some of the leftover is definition, not physics, and CAMELS boxes are small. It shows what the dials can and cannot reach, not which code is right.
Usage: python3 scripts/explore_tune_to_observations.py   Writes data/analysis/tune-to-observations.json and docs/ANALYSIS-tune-to-observations.md"""
import json
from pathlib import Path

import numpy as np
from scipy.optimize import minimize

ROOT = Path(__file__).resolve().parent.parent
CODES = ("IllustrisTNG", "SIMBA")
SHORT = {"IllustrisTNG": "TNG", "SIMBA": "SIMBA"}


def load():
    D = json.loads((ROOT / "data" / "retune" / "retune.json").read_text())
    em = {}
    for c in CODES:
        q = D["codes"][c]
        em[c] = (q["terms"], np.array([[np.nan if v is None else v for v in row] for row in q["coef"]], float))
    return D, em


def predict(em, a, idx):
    terms, coef = em
    t = np.array([np.prod([a[j] for j in tm]) if tm else 1.0 for tm in terms])
    return t @ coef[:, idx]


def target(D, fam, snap, x, y):
    """The observed curve on the simulated bins it spans, interpolated linearly, as the page does; None if fewer than three bins."""
    ids = D["blocks"].get(f"{fam}|{snap}")
    if not ids:
        return None
    pts = sorted((a, b) for a, b in zip(x, y) if b is not None and np.isfinite(b))
    if len(pts) < 2:
        return None
    px, py = np.array([p[0] for p in pts]), np.array([p[1] for p in pts])
    idx, yy = [], []
    for i in ids:
        xc = D["families"][fam]["x_centres"][D["outputs"][i]["b"]]
        if xc < px[0] or xc > px[-1]:
            continue
        idx.append(i)
        yy.append(float(np.interp(xc, px, py)))
    return (np.array(idx), np.array(yy)) if len(idx) >= 3 else None


def tune(em, idx, yy, scale, rng):
    f = lambda a: float(np.sqrt(np.mean(((predict(em, a, idx) - yy) / scale[idx]) ** 2)))
    best = (np.inf, None)
    for a0 in [np.zeros(4)] + [rng.uniform(-1, 1, 4) for _ in range(24)]:
        r = minimize(f, a0, method="L-BFGS-B", bounds=[(-1, 1)] * 4)
        if r.fun < best[0]:
            best = (float(r.fun), r.x)
    a = best[1]
    dex = float(np.sqrt(np.mean((predict(em, a, idx) - yy) ** 2)))
    return best[0], dex, a


def main():
    D, em = load()
    scale = np.array(D["scale"], float)
    rng = np.random.default_rng(20261020)
    snaps = {s["id"]: s["z"] for s in D["snapshots"]}
    rows = []
    for o in D["overlays"]:
        if o["kind"] != "observation" or o["family"] not in D["families"] or not D["families"][o["family"]].get("joint"):
            continue
        t = target(D, o["family"], o["snapshot"], o["x"], o["y"])
        if t is None:
            continue
        idx, yy = t
        r = {"family": o["family"], "snapshot": o["snapshot"], "z": snaps[o["snapshot"]], "source": o["source"], "label": o["label"], "tier": o.get("tier"), "bins": int(len(idx))}
        for c in CODES:
            g, dex, a = tune(em[c], idx, yy, scale, rng)
            r[c] = {"gap": g, "dex": dex}
        rows.append(r)
    out = {"rows": rows, "n": len(rows)}
    (ROOT / "data" / "analysis" / "tune-to-observations.json").write_text(json.dumps(out, indent=1) + "\n")
    (ROOT / "docs" / "ANALYSIS-tune-to-observations.md").write_text(render(D, rows))
    ok = sum(1 for r in rows if min(r[c]["gap"] for c in CODES) <= 1.0)
    print(f"tune to observations: {len(rows)} observed curves; at least one code within one noise unit on {ok}")


def fam_line(rows, f):
    rs = [r for r in rows if r["family"] == f]
    return "; ".join(f"{SHORT[c]} within one noise unit on {sum(1 for r in rs if r[c]['gap'] <= 1.0)} of {len(rs)}" for c in CODES)


def render(D, rows):
    N = D["family_names"] if isinstance(D["family_names"], dict) else {f: D["families"][f]["title"] for f in D["families"]}
    L = ["# After tuning, how far is each code from the observations? (exploratory)", "",
         "Generated by `scripts/explore_tune_to_observations.py`. For each observed curve on the dials page, each code's four dials are searched for the setting that reproduces it on the simulated mass bins it covers. The leftover is the root-mean-square difference in dex and in the page's noise units (1 = the scatter between one run of each code).", "",
         "**This is not a test of either code.** An observed curve is defined differently from the simulated one (aperture, initial mass function, how galaxies are selected and counted), CAMELS boxes are small (25 Mpc/h) and the simulations are not calibrated to be compared at this level, so part of every leftover is definition, not physics. What the table shows is what turning the four dials can and cannot reach.", "",
         "| property | observation | z | bins | TNG leftover (dex / noise units) | SIMBA leftover (dex / noise units) |", "|---|---|---|---|---|---|"]
    for r in sorted(rows, key=lambda r: (r["family"], r["z"], r["source"])):
        T, S = r["IllustrisTNG"], r["SIMBA"]
        L.append(f"| {D['families'][r['family']]['title']} | {r['source'] if r['label'] in r['source'] or r['source'] in r['label'] else r['source'] + ' (' + r['label'] + ')'} | {r['z']:.2f} | {r['bins']} | {T['dex']:.2f} / {T['gap']:.1f} | {S['dex']:.2f} / {S['gap']:.1f} |")
    n = len(rows)
    both = sum(1 for r in rows if max(r[c]["gap"] for c in CODES) <= 1.0)
    one = sum(1 for r in rows if min(r[c]["gap"] for c in CODES) <= 1.0)
    L += ["", "## Reading", "",
          f"{n} observed curves could be compared. Both codes get within one noise unit of {both}; at least one does on {one}. By property: " + "; ".join(f"{D['families'][f]['title'].lower().replace('sfr', 'SFR')}: {fam_line(rows, f)}" for f in sorted({r['family'] for r in rows})) + ". A smooth curve with a few bins is easy to fit with four dials, so being within one noise unit of the stellar mass function or the quenched fraction is weak evidence of anything; being far off, as for the black hole mass, is the informative outcome. A leftover over one noise unit says only that no setting of the four dials of that code reproduces the curve to the run-to-run scatter, which given the definition differences above is the expected state for many observations and says nothing against either code in particular.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    main()
