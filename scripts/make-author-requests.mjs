import { readFile, readdir, writeFile } from "node:fs/promises";
const root = new URL("../", import.meta.url);
const release = JSON.parse(await readFile(new URL("data/release.json", root), "utf8"));
const by = new Map();
for (const f of (await readdir(new URL("data/curves/", root))).filter(f => f.endsWith(".json"))) {
  for (const r of JSON.parse(await readFile(new URL(`data/curves/${f}`, root), "utf8")).records) {
    if (r.kind !== "simulation" || r.provenance.tier !== "digitized-figure") continue;
    const key = r.provenance.doi || r.provenance.url;
    const e = by.get(key) || by.set(key, { doi: r.provenance.doi, url: r.provenance.url, cite: (r.provenance.citation.match(/^(.+? \d{4}, [^,]+? \d+, [A-Za-z0-9]+)/) || [0, r.provenance.citation])[1].replace(/,\s*(Fig\.|SFR-M|HI-tests|\(doi).*$/, ""), sources: new Set(), relations: new Set(), n: 0, z: [] }).get(key);
    e.sources.add(r.source);
    e.relations.add(r.relation);
    e.n++;
    e.z.push(r.epoch.zRepresentative);
  }
}
const rows = [...by.values()].sort((a, b) => b.n - a.n || a.cite.localeCompare(b.cite));
const total = rows.reduce((s, e) => s + e.n, 0);
const L = [
  "# Author requests: replacing digitized curves with released tables",
  "",
  `Generated by \`scripts/make-author-requests.mjs\` from dataset v${release.version}. Each row is a paper from which sim-highline holds digitized-figure records of a simulation. A table from the authors would turn those records into \`official-table\` records (exact values, rankable where definitions allow) and remove the digitization uncertainty. ${rows.length} papers, ${total} records.`,
  "",
  "## What to ask for",
  "",
  "A plain text or CSV file with, for each curve in the figure: the x and y values as plotted, the bin edges or the sampling, the unit conventions (h-free? comoving?), the exact mass and aperture definitions, the IMF, and the cosmology. Permission to redistribute the values with a citation to the paper. The wording below can be pasted into an email.",
  "",
  "> Dear Dr X, I maintain sim-highline, an open dataset of galaxy scaling relations from simulations and observations (definition-aware, citation-first). I currently read your Figure N by script from the PDF vector paths, which is exact to the plotted line but not to your data. If you could share the underlying values of the curves in that figure, with the definitions used, I would replace my records with yours (credited, with a link to your data) and list your simulation under official tables. Thank you, Shubhan Bhatia",
  "",
  "## Papers, most records first",
  "",
  "| records | simulations | relations | redshifts | paper | link |",
  "|---:|---|---|---|---|---|",
  ...rows.map(e => {
    const zs = [...new Set(e.z)].sort((a, b) => a - b);
    const zr = zs.length > 1 ? `${+zs[0].toFixed(2)} to ${+zs[zs.length - 1].toFixed(2)}` : `${+zs[0].toFixed(2)}`;
    return `| ${e.n} | ${[...e.sources].sort().join(", ")} | ${[...e.relations].sort().join(", ")} | ${zr} | ${e.cite.replaceAll("|", "/")} | ${e.doi ? `[doi](https://doi.org/${e.doi})` : `[link](${e.url})`} |`;
  }),
  ""
];
await writeFile(new URL("docs/author-requests.md", root), L.join("\n"));
console.log(`Author requests: ${rows.length} papers, ${total} digitized simulation records`);
